"""Conversation intelligence — summary, topics, Q&A, overlaps, silence, sentiment, actions."""
from __future__ import annotations

from html import escape

import pandas as pd
import plotly.graph_objects as go
import streamlit as st

from core.conversation_summary import ollama_status, ollama_summarize, with_display_names
from database.db import session_scope
from database.models import AnalysisResult
from ui.components import (PLOTLY_CONFIG, chip, load, metrics_row, names_and_colors, note, page_header,
                           recording_picker, section, settings, style_fig)
from utils.time_formatter import format_duration, format_percent, format_timestamp

page_header("Analysis", "Conversation intelligence",
            "Measured audio facts are tagged in blue; text-based estimates from local NLP are tagged in violet.")
rid = recording_picker()
if not rid:
    st.stop()
data = load(rid)
m = data["metrics"]
names, colors = names_and_colors(data)
s = settings()
N = lambda l: names.get(l, l or "Unknown")  # noqa: E731


def speaker_html(label):
    return chip(N(label), colors.get(label, "#64748B"))


def insight_list(items, empty="None detected.", extra=None):
    if not items:
        st.caption(empty)
        return
    for x in items:
        meta = f'{format_timestamp(x["start"])} · {speaker_html(x.get("speaker"))} · confidence {x.get("confidence", 0):.0%}'
        if extra:
            meta += extra(x)
        st.markdown(f'<div class="tt-seg"><div class="tt-seg-head">{meta}</div><div class="tt-seg-text">{escape(x["text"])}</div></div>',
                    unsafe_allow_html=True)


tabs = st.tabs(["Summary", "Topics & key points", "Questions", "Overlaps", "Silence", "Sentiment", "Decisions & actions", "Participation"])

# ---------------------------------------------------------------- summary
with tabs[0]:
    section("Conversation summary", "Built only from measured statistics and rule-based extraction — no generative model.", tag="inferred")
    st.markdown(f'<div class="tt-card"><div class="tt-seg-text">{escape(with_display_names(m.get("summary", ""), names))}</div></div>', unsafe_allow_html=True)
    ins = m.get("insights", {})
    q = m.get("questions", {})
    it = m.get("interruptions", {})
    st.write("")
    metrics_row([
        ("Questions", str(q.get("total_questions", 0)), f"{q.get('possibly_unanswered', 0)} possibly unanswered", None),
        ("Possible interruptions", str(it.get("possible_interruptions", 0)), f"{it.get('interruptions_per_minute', 0):.2f} per minute", None),
        ("Decisions / actions", f"{len(ins.get('decision', []))} / {len(ins.get('action_item', []))}", "Rule-based detection", None),
        ("Longest silence", format_duration(m.get("silence", {}).get("longest_silence")), "No one speaking", None),
    ])
    section("Local LLM summary", "Optional. Uses an Ollama model running on this computer.", tag="optional")
    llm = m.get("llm_summary") or {}
    if llm.get("text"):
        st.markdown(f"*Generated by {escape(llm['model'])} — generative output may contain errors.*")
        st.markdown(llm["text"])
    elif llm.get("error"):
        st.warning(llm["error"])
    if not s.ollama_enabled:
        st.caption("Ollama integration is disabled. Enable it in Settings → Local LLM. All other features work without it.")
    elif st.button("Generate summary with Ollama", icon=":material/auto_awesome:"):
        status = ollama_status(s.ollama_url)
        if not status["available"]:
            st.error(status["reason"])
        else:
            with st.spinner(f"Running {s.ollama_model} locally…"):
                try:
                    text = ollama_summarize(data["transcript"], s.ollama_url, s.ollama_model)
                    with session_scope() as sess:
                        row = sess.query(AnalysisResult).filter_by(recording_id=rid).one()
                        row.metrics = {**row.metrics, "llm_summary": {"model": s.ollama_model, "text": text}}
                    st.rerun()
                except Exception as exc:
                    st.error(f"Ollama request failed: {exc.__class__.__name__}")

# ---------------------------------------------------------------- topics
with tabs[1]:
    topics = m.get("topics", [])
    section("Main topics", "Frequent noun phrases and named entities (spaCy, local).", tag="inferred")
    if topics:
        fig = go.Figure(go.Bar(y=[t["topic"] for t in topics], x=[t["mentions"] for t in topics], orientation="h",
                               marker=dict(color="#9085E9", cornerradius=4),
                               customdata=[[format_timestamp(t["first_mention"]), ", ".join(N(x) for x in t["speakers"])] for t in topics],
                               hovertemplate="<b>%{y}</b><br>weighted mentions %{x}<br>first at %{customdata[0]}<br>by %{customdata[1]}<extra></extra>"))
        fig.update_yaxes(autorange="reversed")
        fig.update_xaxes(title="weighted mentions")
        st.plotly_chart(style_fig(fig, 60 + 34 * len(topics), legend=False), width="stretch", theme=None, config=PLOTLY_CONFIG)
    else:
        st.caption("Not enough repeated content to identify topics (or the language is not English).")
    section("Key points", "Extractive: sentences with the highest density of topic terms and emphasis cues.", tag="inferred")
    insight_list([dict(k, confidence=min(0.9, 0.4 + k.get("score", 0) / 20)) for k in m.get("key_points", [])])

# ---------------------------------------------------------------- questions
with tabs[2]:
    q = m.get("questions", {})
    section("Questions and responses", q.get("method", ""), tag="inferred")
    per = q.get("per_speaker", {})
    if per:
        st.dataframe(pd.DataFrame([{"Speaker": N(k), "Asked": v["asked"], "Got a response": v["got_response"],
                                    "Possibly unanswered": v["possibly_unanswered"], "Responded to others": v["responded_to_others"]}
                                   for k, v in per.items()]), hide_index=True, width="stretch")
    filt = st.segmented_control("Show", ["All", "Likely answered", "Possibly unanswered"], default="All")
    for x in q.get("questions", []):
        if filt == "Likely answered" and not x["answered"] or filt == "Possibly unanswered" and x["answered"]:
            continue
        with st.container(border=True):
            st.markdown(f'<div class="tt-seg-head">{format_timestamp(x["start"])} · {speaker_html(x["speaker"])} · '
                        f'detection {x["confidence"]:.0%} ({escape(x["method"])})</div>'
                        f'<div class="tt-seg-text"><b>Q:</b> {escape(x["text"])}</div>', unsafe_allow_html=True)
            if x["answered"]:
                st.markdown(f'<div class="tt-seg" style="border-left-color:{colors.get(x["answered_by"], "#64748B")}">'
                            f'<div class="tt-seg-head">{speaker_html(x["answered_by"])} · after {x["response_delay"]:.1f}s · '
                            f'match confidence {x["answer_confidence"]:.0%}</div><div class="tt-seg-text">{escape(x["answer_text"])}</div></div>',
                            unsafe_allow_html=True)
            else:
                st.markdown('<span class="tt-badge tt-badge-warn">! Possibly unanswered</span>', unsafe_allow_html=True)
    if not q.get("questions"):
        st.caption("No questions detected.")

# ---------------------------------------------------------------- overlaps
with tabs[3]:
    it = m.get("interruptions", {})
    section("Overlapping speech and possible interruptions", it.get("note", ""), tag="measured")
    counts = it.get("counts", {})
    from core.interruption_analysis import LABELS
    metrics_row([(LABELS[k], str(counts.get(k, 0)), "", None) for k in LABELS])
    st.write("")
    per = it.get("per_speaker", {})
    if per:
        df = pd.DataFrame([{"Speaker": N(k), "Started overlap (possible interruption)": v["initiated"],
                            "Was overlapped (possible interruption)": v["received"], "All overlap events": v["overlap_events"]}
                           for k, v in per.items()])
        st.dataframe(df, hide_index=True, width="stretch")
    ev = it.get("events", [])
    if ev:
        st.dataframe(pd.DataFrame([{"Time": format_timestamp(e["start"], True), "Type": e["label"],
                                    "Already speaking": N(e["ongoing_speaker"]) if e["ongoing_speaker"] else "—",
                                    "Started speaking": N(e["incoming_speaker"]) if e["incoming_speaker"] else "—",
                                    "Overlap": f"{e['duration']:.1f}s"} for e in ev]), hide_index=True, width="stretch")
    else:
        st.caption("No overlapping speech above the configured threshold.")

# ---------------------------------------------------------------- silence
with tabs[4]:
    si = m.get("silence", {})
    th = si.get("thresholds", {})
    section("Silence and pauses", f"Silence = no diarized speech for at least {th.get('min_silence', 1)}s. "
            "Shorter gaps are normal pauses and are not counted.", tag="measured")
    metrics_row([
        ("Total silence", format_duration(si.get("total_silence")), f"{si.get('num_silences', 0)} silences", None),
        ("Longest silence", format_duration(si.get("longest_silence")), f"{si.get('num_long_silences', 0)} ≥ {th.get('long_silence', 5)}s", None),
        ("Average silence", format_duration(si.get("average_silence")), "Across all silences", None),
        ("Median response delay", format_duration(si.get("response_delay_stats", {}).get("median")), "At speaker changes", None),
    ])
    left, right = st.columns(2, gap="large")
    with left:
        section("Response delay by speaker", "Gap before a speaker replies to someone else.")
        rd = si.get("response_delay_by_speaker", {})
        if rd:
            fig = go.Figure(go.Bar(x=[N(k) for k in rd], y=[v["median"] for v in rd.values()],
                                   marker=dict(color=[colors.get(k, "#64748B") for k in rd], cornerradius=4),
                                   customdata=[[v["mean"], v["max"], v["count"]] for v in rd.values()],
                                   hovertemplate="<b>%{x}</b><br>median %{y:.2f}s · mean %{customdata[0]:.2f}s<br>max %{customdata[1]:.1f}s · n=%{customdata[2]}<extra></extra>"))
            fig.update_yaxes(title="median delay (s)")
            st.plotly_chart(style_fig(fig, 280, legend=False), width="stretch", theme=None, config=PLOTLY_CONFIG)
        else:
            st.caption("No speaker changes.")
    with right:
        section("Silence breakdown")
        kinds = {}
        for x in si.get("silences", []):
            kinds[x["kind"]] = kinds.get(x["kind"], 0) + x["duration"]
        if kinds:
            labels_map = {"leading": "Before first speech", "trailing": "After last speech", "within_speaker": "Pause within a speaker",
                          "between_speakers": "Gap between speakers"}
            fig = go.Figure(go.Bar(y=[labels_map[k] for k in kinds], x=list(kinds.values()), orientation="h",
                                   marker=dict(color="#64748B", cornerradius=4), hovertemplate="%{y}: %{x:.1f}s<extra></extra>"))
            fig.update_xaxes(title="seconds")
            st.plotly_chart(style_fig(fig, 280, legend=False), width="stretch", theme=None, config=PLOTLY_CONFIG)
    ac = m.get("acoustic_silence") or {}
    if ac.get("threshold_db") is not None:
        note(f"Acoustic check: {format_duration(ac['total'])} of low-energy audio in {ac['count']} region(s) below "
             f"{ac['threshold_db']} dBFS (adaptive threshold). This differs from speech-based silence because background "
             "noise or music can fill gaps without speech.")

# ---------------------------------------------------------------- sentiment
with tabs[5]:
    se = m.get("sentiment", {})
    section("Language sentiment", se.get("disclaimer", ""), tag="inferred")
    if not se.get("available"):
        st.info(se.get("reason", "Sentiment not available."))
    else:
        left, right = st.columns([2, 3], gap="large")
        with left:
            per = se.get("per_speaker", {})
            rows = []
            for k, v in per.items():
                n = sum(v["distribution"].values()) or 1
                rows.append((N(k), [v["distribution"].get(c, 0) / n * 100 for c in ("negative", "neutral", "positive")]))
            fig = go.Figure()
            for idx, (cat, col) in enumerate((("Negative", "#D55181"), ("Neutral", "#64748B"), ("Positive", "#199E70"))):
                fig.add_bar(y=[r[0] for r in rows], x=[r[1][idx] for r in rows], name=cat, orientation="h",
                            marker=dict(color=col, line=dict(color="#0B1120", width=2)),
                            hovertemplate="%{y}: %{x:.0f}% " + cat.lower() + "<extra></extra>")
            fig.update_layout(barmode="stack")
            fig.update_xaxes(range=[0, 100], ticksuffix="%")
            st.plotly_chart(style_fig(fig, 80 + 50 * len(rows)), width="stretch", theme=None, config=PLOTLY_CONFIG)
            st.caption("Share of each speaker's segments classified as negative / neutral / positive.")
        with right:
            tl = pd.DataFrame(se.get("timeline", []))
            if not tl.empty:
                fig = go.Figure()
                fig.add_hline(y=0, line=dict(color="#475569", width=1))
                for k in tl["speaker"].unique():
                    d = tl[tl["speaker"] == k]
                    fig.add_scatter(x=d["time"], y=d["score"], mode="markers", name=N(k),
                                    marker=dict(color=colors.get(k, "#64748B"), size=8, line=dict(color="#0B1120", width=2)),
                                    customdata=d["time"].map(format_timestamp),
                                    hovertemplate="%{customdata} · score %{y:+.2f}<extra>" + escape(N(k)) + "</extra>")
                fig.add_scatter(x=tl["time"], y=tl["rolling"], mode="lines", name="Rolling average",
                                line=dict(color="#E2E8F0", width=2), hovertemplate="rolling %{y:+.2f}<extra></extra>")
                fig.update_yaxes(range=[-1.05, 1.05], title="sentiment score")
                tv = [tl["time"].max() * k / 6 for k in range(7)]
                fig.update_xaxes(tickvals=tv, ticktext=[format_timestamp(t) for t in tv])
                st.plotly_chart(style_fig(fig, 320), width="stretch", theme=None, config=PLOTLY_CONFIG)
        tr = se.get("trend")
        if tr:
            direction = "more positive" if tr["change"] > 0.1 else "more negative" if tr["change"] < -0.1 else "broadly stable"
            st.markdown(f"Wording became **{direction}** over the conversation (first third {tr['first_third']:+.2f} → last third {tr['last_third']:+.2f}).")

# ---------------------------------------------------------------- decisions
with tabs[6]:
    ins = m.get("insights", {})
    deadline = lambda x: f' · <span class="tt-badge tt-badge-info">• {escape(x["deadline"])}</span>' if x.get("deadline") else ""  # noqa: E731
    section("Possible decisions", "Matched phrases such as “we decided”, “let's go with”, “agreed”.", tag="inferred")
    insight_list(ins.get("decision", []))
    section("Possible action items", "Requests and obligations (“can you…”, “need to…”, deadlines).", tag="inferred")
    insight_list(ins.get("action_item", []), extra=deadline)
    section("Commitments", "First-person promises (“I'll…”, “I will…”).", tag="inferred")
    insight_list(ins.get("commitment", []), extra=deadline)
    section("Important statements", "Sentences flagged by emphasis cues (“important”, “risk”, “priority”…).", tag="inferred")
    insight_list(ins.get("important", []))

# ---------------------------------------------------------------- participation
with tabs[7]:
    pa = m.get("participation", {})
    section("Participation balance", pa.get("method", ""), tag="measured")
    score = pa.get("balance_score")
    metrics_row([
        ("Balance score", "—" if score is None else f"{score:.2f}", pa.get("balance_label", ""), None),
        ("Turn balance", "—" if pa.get("turn_balance_score") is None else f"{pa['turn_balance_score']:.2f}", "Entropy of turn counts", None),
        ("Most active", N(pa.get("dominant_speaker")) if pa.get("dominant_speaker") else "—", format_percent(pa.get("dominant_share")), None),
    ])
    ts, tt = pa.get("time_share", {}), pa.get("turn_share", {})
    if ts:
        fig = go.Figure()
        fig.add_bar(x=[N(k) for k in ts], y=[v * 100 for v in ts.values()], name="Speaking time",
                    marker=dict(color=[colors.get(k) for k in ts], cornerradius=4), hovertemplate="%{x}: %{y:.1f}% of time<extra></extra>")
        fig.add_bar(x=[N(k) for k in tt], y=[v * 100 for v in tt.values()], name="Turns",
                    marker=dict(color=[colors.get(k) for k in tt], pattern=dict(shape="/", fgcolor="#0B1120", size=6), cornerradius=4),
                    hovertemplate="%{x}: %{y:.1f}% of turns<extra></extra>")
        if len(ts) > 1:
            fig.add_hline(y=100 / len(ts), line=dict(color="#94A3B8", dash="dot", width=1),
                          annotation_text="equal share", annotation_font_color="#94A3B8")
        fig.update_layout(barmode="group")
        fig.update_yaxes(ticksuffix="%")
        st.plotly_chart(style_fig(fig, 320), width="stretch", theme=None, config=PLOTLY_CONFIG)
        st.caption("Solid bars: share of speaking time. Hatched bars: share of turns.")
    for w in pa.get("warnings", []):
        st.warning(with_display_names(w, names), icon=":material/info:")
    note(pa.get("caveat", ""))
